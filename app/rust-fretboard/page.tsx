'use client';

import {useRef, useState} from 'react';
import Link from 'next/link';
import styles from './page.module.css';

type Geometry = {length:number;frets:{number:number;x:number;width:number}[];svg:string};
export default function RustFretboard() {
  const [geometry,setGeometry]=useState<Geometry|null>(null);
  const [message,setMessage]=useState('Enter dimensions in millimeters, then generate.');
  const [busy,setBusy]=useState(false);
  const serial=useRef(0);
  function invalidate(){serial.current++;setGeometry(null);setBusy(false);setMessage('Dimensions changed. Generate a new template.');}
  async function generate(event:React.FormEvent<HTMLFormElement>) {
    event.preventDefault();const form=new FormData(event.currentTarget),token=++serial.current;
    setBusy(true);setGeometry(null);setMessage('Calculating with Rust…');
    try {
      const response=await fetch('/api/v1/fretboard',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(Object.fromEntries([...form].map(([k,v])=>[k,Number(v)]))),signal:AbortSignal.timeout(10000)});
      const result=await response.json();
      if(!response.ok||!result.ok)throw new Error(result.error?.message||'Could not generate fretboard.');
      if(token!==serial.current)return;
      setGeometry(result.data);setMessage('Generated by Rust. Print the SVG at 100% / Actual Size.');
    }catch(error){if(token===serial.current)setMessage(error instanceof Error?error.message:'Could not generate fretboard.');}
    finally{if(token===serial.current)setBusy(false);}
  }
  function download() {
    if(!geometry)return;
    const url=URL.createObjectURL(new Blob([geometry.svg],{type:'image/svg+xml'}));
    const a=document.createElement('a');a.href=url;a.download='usonian-rust-fretboard.svg';a.click();
    setTimeout(()=>URL.revokeObjectURL(url),1000);
  }
  return <main className={styles.page}>
    <Link href="/">← Usonian tools</Link><p className={styles.eyebrow}>Rust preview</p>
    <h1>Fretboard generator</h1>
    <p>A simple equal-temperament layout powered by the shared luthier geometry engine.</p>
    <div className={styles.layout}>
      <section className={styles.panel}>
        <form onSubmit={generate} onChange={invalidate}>
          <label>Scale length (mm)<input name="scaleLength" type="number" min="100" max="1500" step="0.001" defaultValue="643.636" required/></label>
          <label>Number of frets<input name="fretCount" type="number" min="1" max="36" step="1" defaultValue="20" required/></label>
          <label>Nut width (mm)<input name="nutWidth" type="number" min="10" max="150" step="0.01" defaultValue="44.45" required/></label>
          <label>Width at final fret (mm)<input name="endWidth" type="number" min="10" max="150" step="0.01" defaultValue="58" required/></label>
          <button type="submit" disabled={busy}>{busy?'Calculating…':'Generate template'}</button>
        </form>
        <button type="button" onClick={download} disabled={!geometry}>Download SVG</button>
        <p role="status" aria-live="polite">{message}</p>
        <p className={styles.note}>The outline ends at the final fret. This preview includes fret centerlines and a straight taper; it has no slot-width compensation, end extension, or surface radius.</p>
        <a href="/side-template/?engine=rust">Open the side/top Rust preview →</a>
      </section>
      <section className={styles.panel} aria-label="Fretboard preview">
        {geometry?<>
          {/* eslint-disable-next-line @next/next/no-img-element -- Generated SVG has physical units and must bypass image optimization. */}
          <img className={styles.preview} src={'data:image/svg+xml;charset=utf-8,'+encodeURIComponent(geometry.svg)} alt="Fretboard outline and fret centerlines"/>
          <p>Nut to final fret: {geometry.length.toFixed(3)} mm</p>
          <div className={styles.table}><table><thead><tr><th>Fret</th><th>From nut (mm)</th><th>Width (mm)</th></tr></thead><tbody>{geometry.frets.map(f=><tr key={f.number}><td>{f.number}</td><td>{f.x.toFixed(3)}</td><td>{f.width.toFixed(3)}</td></tr>)}</tbody></table></div></>:<p>Your generated template will appear here.</p>}
      </section>
    </div>
  </main>;
}
